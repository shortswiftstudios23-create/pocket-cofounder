// The only door to Gemini for the app. Checks the user, enforces the daily cap, softens serious topics, returns plain text.
import { admin, cors, json, userFrom } from '../_shared/util.ts';
import { AIError, aiConfigured, gemini, reserveAI } from '../_shared/gemini.ts';
import { AI_TASKS, MAX_IMAGE_B64, clip, MAX_INPUT, isSerious, systemPrompt, userPrompt, type AITask } from '../../../src/core/aiprompt.ts';

Deno.serve(async req => {
  if (req.method === 'OPTIONS') return new Response('ok', { headers: cors });
  const user = await userFrom(req); if (!user) return json({ error: 'unauthorized' }, 401);
  let b: Record<string, unknown>; try { b = await req.json(); } catch { return json({ error: 'bad json' }, 400); }
  const task = b.task as AITask; if (!AI_TASKS.includes(task) || task === 'ping_copy') return json({ error: 'bad task' }, 400); // ping copy is generated by ping-engine itself
  const input = clip(String(b.input ?? ''), MAX_INPUT), memory = String(b.memorySummary ?? '');
  const image = typeof b.imageBase64 === 'string' && b.imageBase64.length <= MAX_IMAGE_B64 ? b.imageBase64 : undefined;
  if (!aiConfigured()) return json({ error: 'AI is not configured', code: 'not_configured' }, 503);
  const db = admin(); const { data: p } = await db.from('profiles').select('tz, trust_level').eq('id', user.id).single();
  if (!(await reserveAI(db, user.id, p?.trust_level ?? 0, p?.tz ?? 'UTC'))) return json({ error: 'Daily AI limit reached. It resets tomorrow.', code: 'cap' }, 429);
  try {
    const text = await gemini({ system: systemPrompt(task), user: userPrompt(memory, input), imageBase64: image, maxTokens: task === 'review' ? 400 : 250 });
    return json({ text, softened: isSerious(input) });
  } catch (e) { return json({ error: (e as Error).message, code: e instanceof AIError ? e.code : 'upstream' }, 502); }
});
